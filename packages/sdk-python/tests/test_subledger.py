@pytest.mark.parametrize("case", VECTORS["statements"], ids=lambda c: c["input"]["response_type"])
def test_response_statement_matches_typescript(case):
    given = case["input"]
    statement = build_response_statement(
        given["receipt"],
        given["response_type"],
        given.get("fields"),
        given.get("note"),
        given.get("evidence"),
        given.get("corrections"),
        execution=given.get("execution"),
        issued_at=given.get("issued_at"),
        expires_at=given.get("expires_at"),
        refs=given.get("refs"),
    )
    assert statement == case["statement"]
    assert canonicalize(statement) == case["canonical"]
    assert digest_of(statement) == case["digest"]
    assert sign_statement(statement, VECTORS["private_key"]) == case["signature"]
    assert verify_statement_signature(statement, case["signature"], VECTORS["public_key"])
    assert not verify_statement_signature({**statement, "receipt_revision": statement["receipt_revision"] + 1}, case["signature"], VECTORS["public_key"])


def test_execution_binding_matches_typescript():
    vector = VECTORS["execution_binding"]
    assert execution_binding(vector["descriptor"]) == vector["binding"]


def test_countersignature_matches_typescript():
    vector = VECTORS["countersignature"]
    assert public_key_from_private(VECTORS["private_key"]) == VECTORS["public_key"]
    assert countersign_payload(vector["payload"], VECTORS["private_key"]) == vector["signature"]
    assert verify_countersignature(vector["payload"], vector["signature"], VECTORS["public_key"])
    assert not verify_countersignature({**vector["payload"], "version": 2}, vector["signature"], VECTORS["public_key"])


def test_stable_keys_match_the_typescript_format():
    assert stable_key("financial", "stripe", "evt_1") == "sl:financial:stripe:evt_1"
    long_key = stable_key("task", "x" * 300)
    assert long_key.startswith("sl:task:sha256:") and len(long_key) <= 200
    assert ext("job-42") == "ext:job-42"


# ---------- Fake API server ----------


class FakeApi:
    """Records requests and answers each with the next scripted (status, body); defaults to 200 {}."""

    def __init__(self):
        self.requests: list[dict] = []
        self.responses: list[tuple[int, dict]] = []
        fake = self

        class Handler(BaseHTTPRequestHandler):
            def _handle(self):
                length = int(self.headers.get("content-length") or 0)
                raw = self.rfile.read(length) if length else b""
                fake.requests.append({"method": self.command, "path": self.path, "headers": {k.lower(): v for k, v in self.headers.items()}, "body": raw.decode("utf-8")})
                status, body = fake.responses.pop(0) if fake.responses else (200, {})
                data = json.dumps(body).encode("utf-8")
                self.send_response(status)
                self.send_header("content-type", "application/json")
                self.send_header("content-length", str(len(data)))
                self.end_headers()
                self.wfile.write(data)

            do_GET = do_POST = do_DELETE = _handle

            def log_message(self, *args):
                pass

        self.server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        self.base_url = f"http://127.0.0.1:{self.server.server_address[1]}"
        threading.Thread(target=self.server.serve_forever, daemon=True).start()

    def json_body(self, index: int) -> dict:
        return json.loads(self.requests[index]["body"])


@pytest.fixture
def api():
    fake = FakeApi()
    yield fake
    fake.server.shutdown()


def error(status: int, code: str, retryable: bool) -> tuple[int, dict]:
    return status, {"error": {"code": code, "message": code, "retryable": retryable}}


def test_operator_client_uses_api_key_and_stable_idempotency_keys(api):
    client = SubledgerClient(api.base_url, "atcn_test_key", retries=0)
    client.create_task({"external_ref": "job-42", "currency": "USD"})
    client.get_task(ext("job-42"))
    client.record_financial_event({"type": "charge", "source": "stripe", "source_event_id": "ch_1", "amount_minor": 100, "currency": "USD", "event_date": "2026-10-01T00:00:00.000Z"})
    client.import_csv("type,source\n")

    create, get, charge, csv = api.requests
    assert create["headers"]["authorization"] == "Bearer atcn_test_key"
    assert create["headers"]["idempotency-key"] == "sl:task:job-42"
    assert get["path"] == "/v1/tasks/ext%3Ajob-42"
    assert "idempotency-key" not in get["headers"]
    assert charge["headers"]["idempotency-key"] == "sl:financial:stripe:ch_1"
    assert csv["headers"]["content-type"] == "text/csv"
    assert csv["body"] == "type,source\n"


