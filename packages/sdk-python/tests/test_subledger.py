def test_offering_an_obligation_for_a_task_sends_the_link_outside_the_signed_event(api):
    client = AtcnClient(api.base_url, "atcn_test_key", retries=0)
    signed = {"payload": {"event_id": "evt_1", "event_type": "obligation.offered"}, "signature": {"value": "sig"}}
    client.create_obligation(signed, {"task_id": "ext:job-42"})
    client.create_obligation(signed)

    linked, plain = api.json_body(0), api.json_body(1)
    assert linked == {**signed, "subledger": {"task_id": "ext:job-42"}}
    assert plain == signed
    assert api.requests[0]["headers"]["idempotency-key"] == "event:evt_1"


def test_countersign_signs_locally_and_sends_only_the_signature(api):
    private_key, public_key = generate_key_pair()
    client = SubledgerClient(api.base_url, "atcn_test_key", retries=0)
    closure = {"payload": {"closure_id": "cls_1", "version": 1}, "signature": {}}
    client.countersign(closure, "ops-1", private_key)
    sent = api.json_body(0)
    assert api.requests[0]["path"] == "/v1/closures/cls_1/countersign"
    assert set(sent) == {"key_id", "signature"}
    assert verify_countersignature(closure["payload"], sent["signature"], public_key)
    client.countersign({"payload": {"receipt_id": "rcp_1"}, "signature": {}}, "ops-1", private_key)
    assert api.requests[1]["path"] == "/v1/receipts/rcp_1/countersign"


def test_receipt_link_client_sends_the_share_token_instead_of_an_api_key(api):
    private_key, public_key = generate_key_pair()
    link = ReceiptLinkClient(api.base_url, "shr_tok_secret", retries=0)
    link.current()
    receipt = {"receipt_id": "rcp_1", "digest": "sha256:" + "a" * 64, "revision": 1}
    signing = {"binding_id": "pkb_1", "key_id": "prov-1", "private_key": private_key, "issuer_operator_id": "ten_1"}
    link.respond(receipt, "signed_attestation", ["delivery.status"], signing=signing)

    for request in api.requests:
        assert request["headers"]["x-atcn-share-token"] == "shr_tok_secret"
        assert "authorization" not in request["headers"]
    sent = api.json_body(1)
    assert sent["receipt_revision"] == 1 and sent["provider_signature"]["binding_id"] == "pkb_1"
    statement = build_response_statement({**receipt, "issuer_operator_id": "ten_1"}, "signed_attestation", ["delivery.status"])
    assert verify_statement_signature(statement, sent["provider_signature"]["value"], public_key)


def test_capture_queue_retries_with_one_key_and_never_raises(api):
    queue = CaptureQueue(SubledgerClient(api.base_url, "k", retries=0), max_size=3, max_attempts=2)
    assert queue.task({"external_ref": "job-1", "currency": "USD"})
    assert queue.financial_event({"type": "charge", "source": "stripe", "source_event_id": "ch_9", "amount_minor": 5, "currency": "USD", "event_date": "2026-10-01T00:00:00.000Z"})

    api.responses = [error(503, "retryable_infrastructure_failure", True)]
    assert queue.flush() == {"sent": 0, "failed": 0, "remaining": 2}
    assert queue.flush() == {"sent": 2, "failed": 0, "remaining": 0}
    keys = [r["headers"]["idempotency-key"] for r in api.requests]
    assert keys == ["sl:task:job-1", "sl:task:job-1", "sl:financial:stripe:ch_9"]


def test_capture_queue_overflow_failures_export_replay_and_gaps(api):
    queue = CaptureQueue(SubledgerClient(api.base_url, "k", retries=0), max_size=2, max_attempts=2)
    assert queue.task({"external_ref": "a", "currency": "USD"})
    assert queue.task({"external_ref": "b", "currency": "USD"})
    assert not queue.task({"external_ref": "c", "currency": "USD"})
    assert queue.dropped == 1 and queue.size == 2

    api.responses = [error(400, "validation_error", False)]
    assert queue.flush() == {"sent": 1, "failed": 1, "remaining": 0}
    exported = queue.export_failed()
    assert json.loads(exported)["idempotencyKey"] == "sl:task:a"
    assert queue.replay(exported) == 1 and queue.failed_operations() == []
    queue.flush()
    assert api.requests[-1]["headers"]["idempotency-key"] == "sl:task:a"

    assert queue.report_gaps(ext("job"))
    gap = api.json_body(len(api.requests) - 1)
    assert api.requests[-1]["path"] == "/v1/tasks/ext%3Ajob/capture-gaps"
    assert gap["kind"] == "queue_overflow" and "1 capture operation(s) dropped" in gap["detail"]


def test_capture_queue_survives_an_unreachable_api():
    queue = CaptureQueue(SubledgerClient("http://127.0.0.1:9", "k", retries=0, timeout=1), max_attempts=3)
    queue.task({"external_ref": "offline", "currency": "USD"})
    assert queue.flush() == {"sent": 0, "failed": 0, "remaining": 1}
    assert queue.failed_operations() == []
